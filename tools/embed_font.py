#!/usr/bin/env python3
"""embed_font.py out.cpp name1=file1.ttf name2=file2.ttf ... -> C++ byte arrays (used by the software GUI)."""
import sys
out = open(sys.argv[1], 'w')
out.write('// generated by tools/embed_font.py - Poppins (SIL Open Font License 1.1), see assets/OFL.txt\n#include "font_data.h"\nnamespace df { namespace gui {\n')
names = []
for a in sys.argv[2:]:
    n, f = a.split('=')
    d = open(f, 'rb').read()
    out.write('static const unsigned char k_%s[] = {\n' % n)
    for i in range(0, len(d), 24):
        out.write(','.join(str(b) for b in d[i:i + 24]) + ',\n')
    out.write('};\n')
    names.append((n, len(d)))
for n, l in names:
    out.write('const unsigned char* font_%s() { return k_%s; }\nunsigned font_%s_size() { return %d; }\n' % (n, n, n, l))
out.write('}}\n')
